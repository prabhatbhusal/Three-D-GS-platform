export const DICT: Record<Lang, Record<string, string>> = { en: {}, ne: NE, zh: ZH };
const isLang = (v: unknown): v is Lang => v === 'en' || v === 'ne' || v === 'zh';

function detect(): Lang {
  const q = new URLSearchParams(location.search).get('lang');
  if (isLang(q)) return q;
  try { const s = localStorage.getItem(KEY); if (isLang(s)) return s; } catch { /* private mode */ }
  for (const l of navigator.languages ?? [navigator.language]) {
    const p = l.slice(0, 2).toLowerCase();
    if (p === 'ne' || p === 'zh') return p;
    if (p === 'en') return 'en';
  }
  return 'en';
}

let lang: Lang | null = null;
const listeners = new Set<() => void>();
const current = (): Lang => {
  if (!lang) { lang = detect(); document.documentElement.lang = lang; }
  return lang;
};

export function setLang(l: Lang) {
  lang = l;
  document.documentElement.lang = l;
  try { localStorage.setItem(KEY, l); } catch { /* private mode */ }
  listeners.forEach((f) => f());
}

export function translate(l: Lang, en: string, vars?: Record<string, string | number>) {
  const s = DICT[l][en] ?? en;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}

/** The current language and a translator bound to it; re-renders on a switch.
 *  English on the server, so a server-rendered form hydrates cleanly. */
export function useT() {
  const l = useSyncExternalStore(
    (f) => { listeners.add(f); return () => listeners.delete(f); },
    current,
    () => 'en' as Lang
  );
  return Object.assign((en: string, vars?: Record<string, string | number>) => translate(l, en, vars), { lang: l });
}
